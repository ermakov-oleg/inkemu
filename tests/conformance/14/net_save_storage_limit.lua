local T = require("conformance")

function on_load(ctx)
  ctx:after(1000, function(ctx)
    ctx.net:request({ url = "https://s.test/max", save = { to = "storage", name = "max.bin" } }, function(ctx, res)
      T.value("max_saved", res.saved)
      T.type("max_err", res.err)
      T.value("max_size", ctx.storage:size("max.bin"))
    end)
  end)
  ctx:after(3000, function(ctx)
    ctx.net:request({ url = "https://s.test/over", save = { to = "storage", name = "over.bin" } }, function(ctx, res)
      T.value("over_ok", res.ok)
      T.value("over_saved", res.saved)
      T.value("over_body_len", #res.body)
      T.value("over_bytes", res.bytes)
      T.value("over_err", res.err)
      T.value("over_exists", ctx.storage:exists("over.bin"))
    end)
  end)
end
